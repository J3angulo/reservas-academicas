-- TABLA USUARIO
CREATE TABLE USUARIO (
                         ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         NOMBRE VARCHAR2(100) NOT NULL,
                         CORREO VARCHAR2(150) NOT NULL UNIQUE,
                         TIPO_USUARIO VARCHAR2(30) NOT NULL
);

-- TABLA ESPACIO
CREATE TABLE ESPACIO (
                         ID_ESPACIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         NOMBRE VARCHAR2(100) NOT NULL,
                         TIPO VARCHAR2(30) NOT NULL,
                         CAPACIDAD NUMBER NOT NULL,
                         UBICACION VARCHAR2(100),
                         ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,

                         CONSTRAINT CK_ESPACIO_CAPACIDAD
                             CHECK (CAPACIDAD > 0),

                         CONSTRAINT CK_ESPACIO_ACTIVO
                             CHECK (ACTIVO IN (0, 1))
);

-- TABLA HORARIO
CREATE TABLE HORARIO (
                         ID_HORARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         ID_ESPACIO NUMBER NOT NULL,
                         DIA_SEMANA VARCHAR2(15) NOT NULL,
                         HORA_INICIO VARCHAR2(5) NOT NULL,
                         HORA_FIN VARCHAR2(5) NOT NULL,

                         CONSTRAINT FK_HORARIO_ESPACIO
                             FOREIGN KEY (ID_ESPACIO)
                                 REFERENCES ESPACIO(ID_ESPACIO),

                         CONSTRAINT CK_HORARIO_HORAS
                             CHECK (HORA_INICIO < HORA_FIN)
);

-- TABLA RESERVA
CREATE TABLE RESERVA (
                         ID_RESERVA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         ID_USUARIO NUMBER NOT NULL,
                         ID_ESPACIO NUMBER NOT NULL,
                         FECHA DATE NOT NULL,
                         HORA_INICIO VARCHAR2(5) NOT NULL,
                         HORA_FIN VARCHAR2(5) NOT NULL,
                         ESTADO VARCHAR2(20) DEFAULT 'ACTIVA' NOT NULL,

                         CONSTRAINT FK_RESERVA_USUARIO
                             FOREIGN KEY (ID_USUARIO)
                                 REFERENCES USUARIO(ID_USUARIO),

                         CONSTRAINT FK_RESERVA_ESPACIO
                             FOREIGN KEY (ID_ESPACIO)
                                 REFERENCES ESPACIO(ID_ESPACIO),

                         CONSTRAINT CK_RESERVA_HORAS
                             CHECK (HORA_INICIO < HORA_FIN),

                         CONSTRAINT CK_RESERVA_ESTADO
                             CHECK (ESTADO IN ('ACTIVA', 'CANCELADA'))
);

